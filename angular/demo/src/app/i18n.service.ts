@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly dictionaries: Record<Locale, Dict> = { vi: VI, en: EN };

  private readonly _locale = signal<Locale>(this.readStoredLocale());
  readonly locale = this._locale.asReadonly();

  setLocale(locale: Locale): void {
    this._locale.set(locale);
    localStorage.setItem(STORAGE_KEY, locale);
  }

  /** `params` thay thế các token dạng {key} trong chuỗi dịch, vd t('x', {name: 'Pizza'}). */
  t(key: string, params?: Record<string, string | number>): string {
    const raw = this.dictionaries[this._locale()][key] ?? this.dictionaries.vi[key] ?? key;
    if (!params) {
      return raw;
    }
    return Object.entries(params).reduce(
      (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
      raw,
    );
  }

  private readStoredLocale(): Locale {
    return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'vi';
  }
}
